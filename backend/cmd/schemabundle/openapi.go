package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// commonFile holds the definitions shared by the fiche schemas.
const commonFile = "_common.schema.json"

// OpenAPIComponents turns the fiche schemas of <dir>/fiches into OpenAPI components for the API
// contract (ADR-0035): one component per fiche ("FicheRecipe"), one per common definition
// ("FicheText"), every reference pointing inside the components, no $id nor $schema, a string
// type next to each template constant, and a "Fiche" union discriminated by "template" whose
// mapping is derived from the schemas themselves, so that it cannot drift from them.
func OpenAPIComponents(dir string) ([]byte, error) {
	fichesDir := filepath.Join(dir, "fiches")
	schemas := map[string]any{}

	common, err := readSchema(filepath.Join(fichesDir, commonFile))
	if err != nil {
		return nil, err
	}
	// add refuses a component name used twice (a fiche file and a common definition, or two
	// definitions such as code_block and codeBlock, can collide).
	add := func(name string, component any) error {
		if _, taken := schemas[name]; taken {
			return fmt.Errorf("component %s is defined twice (two schemas share a name)", name)
		}
		schemas[name] = component
		return nil
	}
	defs, ok := common["$defs"].(map[string]any)
	if !ok {
		return nil, fmt.Errorf("%s has no $defs", commonFile)
	}
	names := make([]string, 0, len(defs))
	for name := range defs {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		resolved, err := toComponent(commonFile, defs[name])
		if err != nil {
			return nil, err
		}
		if err := add(componentName(name), resolved); err != nil {
			return nil, err
		}
	}

	files, err := filepath.Glob(filepath.Join(fichesDir, "*.schema.json"))
	if err != nil {
		return nil, fmt.Errorf("list fiche schemas: %w", err)
	}
	sort.Strings(files)
	mapping := map[string]any{}
	var oneOf []any
	for _, file := range files {
		base := filepath.Base(file)
		if strings.HasPrefix(base, "_") {
			continue
		}
		schema, err := readSchema(file)
		if err != nil {
			return nil, err
		}
		delete(schema, "$schema")
		delete(schema, "$id")
		resolved, err := toComponent(base, schema)
		if err != nil {
			return nil, err
		}
		component, _ := resolved.(map[string]any)
		template, err := typeTemplate(base, component)
		if err != nil {
			return nil, err
		}
		name := componentName(strings.TrimSuffix(base, ".schema.json"))
		if err := add(name, component); err != nil {
			return nil, err
		}
		if _, taken := mapping[template]; taken {
			return nil, fmt.Errorf("%s: template %q is already used by another fiche", base, template)
		}
		ref := "#/components/schemas/" + name
		mapping[template] = ref
		oneOf = append(oneOf, map[string]any{"$ref": ref})
	}
	if len(oneOf) == 0 {
		return nil, fmt.Errorf("no fiche schema in %s", fichesDir)
	}
	if _, taken := schemas["Fiche"]; taken {
		return nil, fmt.Errorf("component Fiche is reserved for the union")
	}
	schemas["Fiche"] = map[string]any{
		"description":   "Fiche of an item, in the format of its template (docs/prompt/schemas/fiches). Render it by its template, never by the content type of the item.",
		"oneOf":         oneOf,
		"discriminator": map[string]any{"propertyName": "template", "mapping": mapping},
	}

	var buf bytes.Buffer
	encoder := json.NewEncoder(&buf)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	doc := map[string]any{
		"x-generated": "Generated by backend/cmd/schemabundle from docs/prompt/schemas/fiches. Never edit: run make generate.",
		"components":  map[string]any{"schemas": schemas},
	}
	if err := encoder.Encode(doc); err != nil {
		return nil, fmt.Errorf("encode fiche components: %w", err)
	}
	return buf.Bytes(), nil
}

func readSchema(file string) (map[string]any, error) {
	raw, err := os.ReadFile(file) //nolint:gosec // a schema file of the repository
	if err != nil {
		return nil, fmt.Errorf("read schema: %w", err)
	}
	var schema map[string]any
	if err := json.Unmarshal(raw, &schema); err != nil {
		return nil, fmt.Errorf("parse %s: %w", filepath.Base(file), err)
	}
	return schema, nil
}

// componentName names a fiche file or a common definition: "tech_article" → "FicheTechArticle",
// "textList" → "FicheTextList".
func componentName(name string) string {
	return "Fiche" + pascalCase(name)
}

func pascalCase(name string) string {
	var out strings.Builder
	upper := true
	for _, r := range name {
		if r == '_' || r == '-' {
			upper = true
			continue
		}
		if upper {
			out.WriteString(strings.ToUpper(string(r)))
			upper = false
			continue
		}
		out.WriteRune(r)
	}
	return out.String()
}

// typeTemplate returns the template constant of a fiche and adds `type: string` next to it,
// which oapi-codegen needs to type the field.
func typeTemplate(file string, component map[string]any) (string, error) {
	properties, _ := component["properties"].(map[string]any)
	template, _ := properties["template"].(map[string]any)
	value, ok := template["const"].(string)
	if !ok || value == "" {
		return "", fmt.Errorf("%s: properties.template.const is missing", file)
	}
	template["type"] = "string"
	return value, nil
}

// toComponent rewrites every $ref of node, written in file, to a component of the contract.
func toComponent(file string, node any) (any, error) {
	switch value := node.(type) {
	case map[string]any:
		out := make(map[string]any, len(value))
		for key, child := range value {
			if key == "$ref" {
				ref, _ := child.(string)
				rewritten, err := componentRef(file, ref)
				if err != nil {
					return nil, err
				}
				out[key] = rewritten
				continue
			}
			resolved, err := toComponent(file, child)
			if err != nil {
				return nil, err
			}
			out[key] = resolved
		}
		return out, nil
	case []any:
		out := make([]any, len(value))
		for i, child := range value {
			resolved, err := toComponent(file, child)
			if err != nil {
				return nil, err
			}
			out[i] = resolved
		}
		return out, nil
	default:
		return node, nil
	}
}

// componentRef maps "_common.schema.json#/$defs/text" (or "#/$defs/text" inside the common file)
// to "#/components/schemas/FicheText".
func componentRef(file, ref string) (string, error) {
	target, fragment, _ := strings.Cut(ref, "#")
	name, ok := strings.CutPrefix(fragment, "/$defs/")
	if !ok || strings.Contains(name, "/") {
		return "", fmt.Errorf("%s: unsupported $ref %q", file, ref)
	}
	if target != "" && target != commonFile {
		return "", fmt.Errorf("%s: $ref %q points outside %s", file, ref, commonFile)
	}
	if target == "" && file != commonFile {
		return "", fmt.Errorf("%s: local $ref %q is not supported in a fiche schema", file, ref)
	}
	return "#/components/schemas/" + componentName(name), nil
}
