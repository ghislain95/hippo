// Writes the build-time configuration of the E1 prototype (design D4): the server URL and the
// token, injected in the app and in the share extension, which share nothing at run time
// (ADR-0014). Run it before every `expo prebuild` or `expo run:ios`.
//
//   HIPPO_SPIKE_URL=https://<mac>.<tailnet>.ts.net npm run configure
//
// Without HIPPO_SPIKE_URL the server is the local echo server (simulator only).
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const appDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokenFile = join(appDir, '..', '.spike-token');

const url = (process.env.HIPPO_SPIKE_URL ?? 'http://127.0.0.1:8787').replace(/\/+$/, '');
const parsed = new URL(url);
if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
  throw new Error(`HIPPO_SPIKE_URL must be http or https, got ${url}`);
}
// An http URL is for the simulator only; an https URL gets no ATS exception at all (E1-03).
const local = parsed.protocol === 'http:';

if (!existsSync(tokenFile)) {
  writeFileSync(tokenFile, randomBytes(32).toString('hex') + '\n', { mode: 0o600 });
}
const token = readFileSync(tokenFile, 'utf8').trim();

writeFileSync(join(appDir, '.spike.json'), JSON.stringify({ url, token, local }, null, 2) + '\n');

writeFileSync(
  join(appDir, 'targets', 'share', 'SpikeConfig.swift'),
  `// Generated by scripts/configure.mjs. Never edit, never commit.
import Foundation

enum SpikeConfig {
  static let serverURL = URL(string: ${JSON.stringify(url)})!
  static let token = ${JSON.stringify(token)}
}
`,
);

const ats = local
  ? `  <key>NSAppTransportSecurity</key>
  <dict>
    <key>NSAllowsLocalNetworking</key>
    <true/>
  </dict>
`
  : '';
// One web URL, one text or one image (design D2), instead of the plugin's TRUEPREDICATE.
writeFileSync(
  join(appDir, 'targets', 'share', 'Info.plist'),
  `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/configure.mjs. Never edit, never commit. -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
${ats}  <key>NSExtension</key>
  <dict>
    <key>NSExtensionAttributes</key>
    <dict>
      <key>NSExtensionActivationRule</key>
      <dict>
        <key>NSExtensionActivationSupportsWebURLWithMaxCount</key>
        <integer>1</integer>
        <key>NSExtensionActivationSupportsText</key>
        <true/>
        <key>NSExtensionActivationSupportsImageWithMaxCount</key>
        <integer>1</integer>
      </dict>
    </dict>
    <key>NSExtensionPointIdentifier</key>
    <string>com.apple.share-services</string>
    <key>NSExtensionPrincipalClass</key>
    <string>$(PRODUCT_MODULE_NAME).ShareViewController</string>
  </dict>
</dict>
</plist>
`,
);

console.log(`Configured for ${url}${local ? ' (simulator, local networking allowed)' : ''}`);
