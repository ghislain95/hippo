/**
 * @jest-environment node
 */
const { execFileSync } = require('node:child_process');
const path = require('node:path');

const {
  GENERATED_FILE,
  buildConfigSource,
  checkBuildConfig,
  resolveApiUrl,
  usesPlainHttp,
  withShareConfig,
} = require('./with-share-config');

// A fake token of the accepted shape: never a real one (ADR-0027).
const VALID_TOKEN = 'test-token-0123456789-abcdefghijklmnop';

/** @param {Record<string, string | undefined>} env */
function failureOf(env) {
  try {
    checkBuildConfig(env);
  } catch (error) {
    if (error instanceof Error) return error;
    throw error;
  }
  throw new Error('checkBuildConfig did not fail');
}

describe('The build refuses a configuration without a token or with an insecure URL', () => {
  test('Missing token', () => {
    const error = failureOf({ HIPPO_API_URL: 'https://hippo.example.ts.net' });

    expect(error.message).toContain('HIPPO_API_TOKEN');
  });

  test('Token too short, not echoed', () => {
    const error = failureOf({
      HIPPO_API_URL: 'https://hippo.example.ts.net',
      HIPPO_API_TOKEN: 'abc"def',
    });

    expect(error.message).toContain('HIPPO_API_TOKEN');
    expect(error.message).not.toContain('abc"def');
  });

  test('Plain HTTP to a tailnet address', () => {
    const error = failureOf({
      HIPPO_API_URL: 'http://hippo.example.ts.net',
      HIPPO_API_TOKEN: VALID_TOKEN,
    });

    expect(error.message).toContain('HIPPO_API_URL');
  });

  test('Local backend on the simulator', () => {
    const config = checkBuildConfig({
      HIPPO_API_URL: 'http://127.0.0.1:8080',
      HIPPO_API_TOKEN: VALID_TOKEN,
    });

    expect(config).toEqual({ url: 'http://127.0.0.1:8080', token: VALID_TOKEN });
  });

  test('Default URL', () => {
    const config = checkBuildConfig({ HIPPO_API_TOKEN: VALID_TOKEN });

    expect(config.url).toBe('http://127.0.0.1:8080');
  });

  test('a token with a character outside the allowed set is refused without being echoed', () => {
    const token = `${VALID_TOKEN}\\n`;
    const error = failureOf({ HIPPO_API_TOKEN: token });

    expect(error.message).toContain('HIPPO_API_TOKEN');
    expect(error.message).not.toContain(token);
  });

  test('a URL with a control character or whitespace is refused', () => {
    for (const url of [
      'https://hippo.example.ts.net/\u0001',
      'https://hippo.exa\nmple.ts.net',
      'https://hippo.example.ts.net/a b',
      'https://hippo.example.ts.net/\u0085',
    ]) {
      const error = failureOf({ HIPPO_API_URL: url, HIPPO_API_TOKEN: VALID_TOKEN });

      expect(error.message).toContain('HIPPO_API_URL');
    }
  });

  test('http on localhost is allowed, a URL that does not parse is refused', () => {
    expect(
      checkBuildConfig({ HIPPO_API_URL: 'http://localhost:8080', HIPPO_API_TOKEN: VALID_TOKEN })
        .url,
    ).toBe('http://localhost:8080');
    expect(failureOf({ HIPPO_API_URL: 'hippo', HIPPO_API_TOKEN: VALID_TOKEN }).message).toContain(
      'HIPPO_API_URL',
    );
    expect(
      failureOf({ HIPPO_API_URL: 'ftp://hippo.example.ts.net', HIPPO_API_TOKEN: VALID_TOKEN })
        .message,
    ).toContain('HIPPO_API_URL');
  });
});

describe('The extension receives the same URL and token as the app', () => {
  test('Generated configuration of the extension', () => {
    const config = checkBuildConfig({
      HIPPO_API_URL: 'https://hippo.example.ts.net/',
      HIPPO_API_TOKEN: VALID_TOKEN,
    });
    const source = buildConfigSource(config);

    expect(source).toContain('"https://hippo.example.ts.net"');
    expect(source).not.toContain('"https://hippo.example.ts.net/"');
    expect(source).toContain(`"${VALID_TOKEN}"`);
    expect(source).toMatch(/generated by app\/plugins\/with-share-config\.js/i);
    expect(source).toMatch(/never edit, never commit/i);
  });

  test('The generated file is ignored by git', () => {
    const appDir = path.resolve(path.dirname(require.resolve('./with-share-config')), '..');
    const output = execFileSync('git', ['check-ignore', GENERATED_FILE], {
      cwd: appDir,
      encoding: 'utf8',
    });

    expect(output.trim()).toBe(GENERATED_FILE);
  });

  test('the app reads the same URL, without its trailing slashes', () => {
    expect(resolveApiUrl({ HIPPO_API_URL: 'https://hippo.example.ts.net//' })).toBe(
      'https://hippo.example.ts.net',
    );
    expect(resolveApiUrl({})).toBe('http://127.0.0.1:8080');
  });

  test('the app allows local networking for plain HTTP only, whatever the case of the scheme', () => {
    expect(usesPlainHttp('http://127.0.0.1:8080')).toBe(true);
    expect(usesPlainHttp('HTTP://127.0.0.1:8080')).toBe(true);
    expect(usesPlainHttp('https://hippo.example.ts.net')).toBe(false);
    expect(usesPlainHttp('not a url')).toBe(false);
  });

  test('evaluating the config without any variable does not fail (expo config, expo-doctor, CI)', () => {
    const config = { name: 'Hippo', slug: 'hippo' };

    expect(() => withShareConfig(config)).not.toThrow();
  });
});
