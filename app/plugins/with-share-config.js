// Build-time configuration of the share extension (design D1, ADR-0014, ADR-0016, ADR-0027).
//
// At `expo prebuild` only, it checks HIPPO_API_URL and HIPPO_API_TOKEN, then writes them into
// `targets/share/BuildConfig.generated.swift`, a git-ignored file that the extension's target
// compiles. Evaluating the Expo config (`expo config`, expo-doctor, jest) checks nothing, so that
// the CI, which has no variables, keeps working. Error messages name the variable and the rule,
// never the value.
const fs = require('node:fs');
const path = require('node:path');

const { withDangerousMod } = require('expo/config-plugins');

const DEFAULT_API_URL = 'http://127.0.0.1:8080';
const MIN_TOKEN_LENGTH = 32;
// Characters that stay a plain string literal in Swift and in JavaScript.
const TOKEN_PATTERN = /^[A-Za-z0-9\-._~+/=]+$/;
// Control characters (C0, DEL, C1) and whitespace: `new URL` drops some of them silently, and an
// escape such as \u0001 is not valid in a Swift string literal.
const UNSAFE_URL_CHARACTERS = /[\u0000-\u0020\u007f-\u009f\s]/u;
// On the simulator, these addresses are the Mac; on a device, they are the phone itself.
const LOOPBACK_HOSTS = new Set(['127.0.0.1', 'localhost']);

/** Path of the generated Swift file, relative to the app folder. */
const GENERATED_FILE = 'targets/share/BuildConfig.generated.swift';

/**
 * The server URL the app and the extension use, without its trailing slashes.
 * @param {Record<string, string | undefined>} env
 * @returns {string}
 */
function resolveApiUrl(env) {
  const raw = (env.HIPPO_API_URL ?? '').trim();
  return (raw === '' ? DEFAULT_API_URL : raw).replace(/\/+$/, '');
}

/**
 * Whether the URL is plain HTTP, whatever the case of its scheme: the app then needs
 * `NSAllowsLocalNetworking` (simulator only, design D1). A URL that does not parse is not.
 * @param {string} url
 * @returns {boolean}
 */
function usesPlainHttp(url) {
  try {
    return new URL(url).protocol === 'http:';
  } catch {
    return false;
  }
}

/**
 * Checks the build-time configuration and returns it, or throws.
 * @param {Record<string, string | undefined>} env
 * @returns {{ url: string, token: string }}
 */
function checkBuildConfig(env) {
  const token = env.HIPPO_API_TOKEN ?? '';
  if (token === '') {
    throw new Error('HIPPO_API_TOKEN is missing: set it to the API token of the server.');
  }
  if (token.length < MIN_TOKEN_LENGTH || !TOKEN_PATTERN.test(token)) {
    throw new Error(
      `HIPPO_API_TOKEN must have at least ${MIN_TOKEN_LENGTH} characters, ` +
        'only letters, digits and - . _ ~ + / =.',
    );
  }

  const url = resolveApiUrl(env);
  if (UNSAFE_URL_CHARACTERS.test(url)) {
    throw new Error('HIPPO_API_URL must not hold whitespace or control characters.');
  }
  let parsed;
  try {
    parsed = new URL(url);
  } catch {
    throw new Error('HIPPO_API_URL is not a valid URL.');
  }
  const isHttps = parsed.protocol === 'https:';
  const isLocalHttp = parsed.protocol === 'http:' && LOOPBACK_HOSTS.has(parsed.hostname);
  if (!isHttps && !isLocalHttp) {
    throw new Error(
      'HIPPO_API_URL must be an https URL, or http on 127.0.0.1 or localhost (simulator only).',
    );
  }
  return { url, token };
}

/**
 * Source of the generated Swift file. The values are safe string literals: the URL parsed and
 * JSON-quoted, the token limited to TOKEN_PATTERN.
 * @param {{ url: string, token: string }} config
 * @returns {string}
 */
function buildConfigSource({ url, token }) {
  return `// Generated by app/plugins/with-share-config.js at expo prebuild. Never edit, never commit:
// it holds the API token (ADR-0027).
import Foundation

enum BuildConfig {
  static let serverURL = URL(string: ${JSON.stringify(url)})!
  static let apiToken = ${JSON.stringify(token)}
}
`;
}

/**
 * Expo config plugin: writes the extension's configuration at prebuild.
 * @param {import('expo/config').ExpoConfig} config
 * @returns {import('expo/config').ExpoConfig}
 */
function withShareConfig(config) {
  return withDangerousMod(config, [
    'ios',
    async (modConfig) => {
      const buildConfig = checkBuildConfig(process.env);
      const file = path.join(modConfig.modRequest.projectRoot, GENERATED_FILE);
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, buildConfigSource(buildConfig));
      return modConfig;
    },
  ]);
}

module.exports = withShareConfig;
module.exports.withShareConfig = withShareConfig;
module.exports.checkBuildConfig = checkBuildConfig;
module.exports.buildConfigSource = buildConfigSource;
module.exports.resolveApiUrl = resolveApiUrl;
module.exports.usesPlainHttp = usesPlainHttp;
module.exports.GENERATED_FILE = GENERATED_FILE;
module.exports.DEFAULT_API_URL = DEFAULT_API_URL;
